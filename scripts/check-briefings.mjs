import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

export async function checkBriefings(page,origin,profile){
  const readJson=url=>page.evaluate(async url=>{const response=await fetch(url);if(!response.ok)throw new Error(`Read failed: ${response.status}`);return response.json();},url);
  await page.goto(`${origin}/#briefings`);
  await page.getByRole('button',{name:'Briefing anlegen',exact:true}).first().click();
  await page.getByLabel('Titel',{exact:true}).fill('Creator Grundbriefing <b>Test</b>');
  await page.getByLabel('Empfänger / Profil',{exact:true}).fill('Beispielredaktion');
  await page.getByLabel('Kanäle',{exact:true}).fill('X, Instagram');
  const original='Virtuelles Markenprofil.\nBelegbare Demos statt erfundener Funktionen. <script>alert(1)</script>';
  await page.getByLabel('Briefingtext',{exact:true}).fill(original);
  await page.locator('#ws-editor button[type=submit]').click();
  await page.locator('dialog').waitFor({state:'hidden'});
  await page.locator('.record-title').filter({hasText:'Creator Grundbriefing'}).click();
  assert.equal(await page.locator('dialog script').count(),0);
  await page.getByRole('button',{name:'Fassung bereitstellen',exact:true}).click();
  await page.getByRole('link',{name:'TXT herunterladen · v1',exact:true}).waitFor();
  const record=(await readJson(`${origin}/api/v1/briefings`)).items[0];
  const base=`${origin}/api/v1/briefings/${record.id}`;
  const downloadFile=async revision=>{
    const event=page.waitForEvent('download');
    await page.getByRole('link',{name:`TXT herunterladen · v${revision}`,exact:true}).click();
    const download=await event;
    assert.equal(download.suggestedFilename(),`briefing-${record.id}-v${revision}.txt`);
    return readFile(await download.path(),'utf8');
  };
  const first=await downloadFile(1);
  assert.ok(first.includes(original));
  let editions=await readJson(`${base}/editions`);
  assert.equal(editions.items[0].handed_over_at,null,'Downloading never records delivery');
  assert.equal(createHash('sha256').update(first).digest('hex'),editions.items[0].sha256);
  await page.getByRole('button',{name:'Bearbeiten',exact:true}).click();
  await page.getByLabel('Briefingtext',{exact:true}).fill('Neue belegte Funktion.');
  await page.getByRole('button',{name:'Änderungen speichern',exact:true}).click();
  await page.locator('dialog').waitFor({state:'hidden'});
  await page.locator('.record-title').filter({hasText:'Creator Grundbriefing'}).click();
  assert.equal(await downloadFile(1),first,'Editing preserves existing TXT');
  await page.getByRole('button',{name:'Fassung bereitstellen',exact:true}).click();
  await page.getByRole('link',{name:'TXT herunterladen · v2',exact:true}).waitFor();
  assert.match(await downloadFile(2),/Neue belegte Funktion/);
  await page.locator('.briefing-edition').filter({hasText:'Fassung 2'}).getByRole('button',{name:'Übergabe erfassen',exact:true}).click();
  await page.getByLabel('Übergabe an / über',{exact:true}).fill('Am Handy an den beauftragten Creator übergeben.');
  await page.getByRole('button',{name:'Übergabe vermerken',exact:true}).click();
  await page.getByRole('heading',{name:'Creator Grundbriefing <b>Test</b>',exact:true}).waitFor();
  await page.locator('#briefing-editions').getByText('Am Handy an den beauftragten Creator übergeben.',{exact:false}).waitFor();
  editions=await readJson(`${base}/editions`);
  assert.ok(editions.items[0].handed_over_at);
  assert.equal(editions.items[1].handed_over_at,null);
  await page.setViewportSize({width:390,height:844});
  assert.match(await downloadFile(2),/Neue belegte Funktion/,'TXT download on phone viewport');
  assert.equal(await page.locator('dialog').evaluate(el=>el.scrollWidth>el.clientWidth),false,'Mobile dialog overflow');
  await page.screenshot({path:`artifacts/${profile}-briefings-mobile.png`,fullPage:true});
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Briefing anlegen',exact:true}).first().click();
  await page.getByLabel('Titel',{exact:true}).fill('Kurze Ergänzung');
  await page.getByLabel('Briefingart',{exact:true}).selectOption('addition');
  await page.getByLabel('Empfänger / Profil',{exact:true}).fill('Beispielredaktion');
  await page.getByLabel('Kanäle',{exact:true}).fill('X');
  await page.getByLabel('Grundbriefing suchen',{exact:true}).fill('Creator Grundbriefing');
  await page.getByRole('option').filter({hasText:'Creator Grundbriefing'}).click();
  await page.getByLabel('Fassung des Grundbriefings',{exact:true}).fill('2');
  await page.getByLabel('Briefingtext',{exact:true}).fill('Neues Thema: Anfragen nachvollziehbar wiederholen.');
  await page.locator('#ws-editor button[type=submit]').click();
  await page.locator('dialog').waitFor({state:'hidden'});
  await page.reload();
  await page.locator('.record-title').filter({hasText:'Kurze Ergänzung'}).waitFor();
  await page.setViewportSize({width:1440,height:1080});
  console.log(`Briefings passed (${profile}): revisions, real TXT download, hash, explicit handoff, pinned addition and mobile.`);
}
